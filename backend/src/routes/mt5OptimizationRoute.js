const express=require('express');
const controller=require('../controller/mt5OptimizationController');
const {verifyToken}=require('../middlewares/authJwt');
const router=express.Router();

router.use(verifyToken);
router.route('/sessions').get(controller.listSessions).post(controller.createSession);
router.patch('/sessions/:id',controller.updateSession);
router.get('/sessions/:id/cleanup-preview',controller.getSessionCleanupPreview);
router.post('/sessions/:id/purge-unused-results',controller.purgeUnusedOptimizeResults);
router.get('/sessions/:id/delete-preview',controller.getSessionCleanupPreview);
router.delete('/sessions/:id',controller.deleteSession);
router.get('/sessions/:id/running-backtests',controller.getRunningBacktestCount);
router.get('/sessions/:id/results-state',controller.getResultsState);
router.route('/api-keys').get(controller.listApiKeys).post(controller.createApiKey);
router.post('/api-keys/:id/revoke',controller.revokeApiKey);
router.delete('/api-keys/:id',controller.deleteApiKey);
router.get('/workers',controller.listWorkers);
router.patch('/workers/:id',controller.updateWorker);
router.delete('/workers/:id',controller.deleteWorker);
router.get('/filter-preferences',controller.getFilterPreferences);
router.put('/filter-preferences/:scope',controller.saveFilterPreference);
router.delete('/filter-preferences/:scope',controller.deleteFilterPreference);
router.route('/jobs').get(controller.listJobs).post(controller.createJobs);
router.get('/jobs/selection',controller.listJobSelection);
router.post('/jobs/every-tick',controller.createEveryTickJobs);
router.post('/jobs/:id/cancel',controller.cancelJob);
router.post('/jobs/:id/retry',controller.retryJob);
router.delete('/jobs/:id',controller.deleteJob);
router.get('/results',controller.listResults);
router.get('/results-summary',controller.getResultsSummary);
router.get('/results/:id',controller.getResult);
router.patch('/results/:id/watchlist',controller.setWatchlist);
router.patch('/results/:id/backtest-candidate',controller.setBacktestCandidate);
router.post('/results/:id/start-backtest',controller.startBacktestResult);
router.get('/backtest-candidates',controller.listBacktestCandidates);
router.post('/backtest-candidates/auto-review',controller.autoReviewBacktestCandidates);
router.get('/backtest-candidates/:id/sparkline',controller.getBacktestCandidateSparkline);
router.get('/backtest-candidates/:id',controller.getBacktestCandidate);
router.delete('/backtest-candidates/:id',controller.deleteBacktestCandidate);
router.patch('/backtest-candidates/:id/staging',controller.selectBacktestStaging);
router.post('/backtest-candidates/:id/sync',controller.syncBacktestCandidate);
router.get('/logs',controller.listLogs);

module.exports=router;
